// ---- Admin: user subscription management ----

func requireSubscriptionUserManagement(c *gin.Context, userID int) bool {
	target, err := model.GetUserById(userID, false)
	if err != nil || !canManageTargetRole(c.GetInt("role"), target.Role) {
		common.ApiErrorMsg(c, "无权修改该用户的额度")
		return false
	}
	return true
}

func requireSubscriptionManagement(c *gin.Context, subscriptionID int) bool {
	var sub model.UserSubscription
	if err := model.DB.Select("user_id").First(&sub, subscriptionID).Error; err != nil {
		common.ApiErrorMsg(c, "无权修改该用户的额度")
		return false
	}
	return requireSubscriptionUserManagement(c, sub.UserId)
}

func AdminListUserSubscriptions(c *gin.Context) {
	userId, _ := strconv.Atoi(c.Param("id"))
	if userId <= 0 {
		common.ApiErrorMsg(c, "无效的用户ID")
		return
	}
	target, err := model.GetUserById(userId, false)
	if err != nil || !canManageTargetRole(c.GetInt("role"), target.Role) {
		common.ApiErrorMsg(c, "无权查看该用户的额度")
		return
	}
	subs, err := model.GetUserSubscriptionsForAdmin(userId)
	if err != nil {
		common.ApiError(c, err)
		return
	}
	_, team, err := model.FindWorkspaceMembership(userId)
	if err != nil {
		common.ApiError(c, err)
		return
	}
	if team != nil && team.OwnerUserID != userId {
		team = nil
	}
	c.Header("Cache-Control", "no-store")
	// Preserve the list response for existing clients; the owner metadata also
	// allows selecting an independent team before its first subscription exists.
	c.JSON(200, gin.H{"success": true, "data": subs, "team": team})
}

